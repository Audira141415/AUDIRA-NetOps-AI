/**
 * GET /api/v1/backups - List backups with optional deviceId filter
 */
backupRouter.get('/', authenticateJwt, requirePermission('config.read'), (req: Request, res: Response) => {
  const { deviceId } = req.query;
  const list = deviceId ? BACKUPS_STORE.filter(b => b.deviceId === deviceId) : BACKUPS_STORE;
  res.json({
    success: true,
    data: list,
    total: list.length,
    message: 'Backups retrieved',
  });
});

/**
 * POST /api/v1/backups - Create immediate snapshot
 */
backupRouter.post('/', authenticateJwt, requirePermission('config.write'), (req: AuthenticatedRequest, res: Response) => {
  const { deviceId, backupType = 'RSC_EXPORT' } = req.body;
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  const newBackup: ConfigurationBackup = {
    id: `bkp-${Date.now()}`,
    deviceId,
    backupType,
    filename: `manual-backup-${timestamp}.${backupType === 'BINARY_BACKUP' ? 'backup' : 'rsc'}`,
    hash: 'd4e5f6a1b2c37890123456789abcdef0123456789abcdef0123456789abcdef',
    sizeBytes: 19800,
    content: '/interface bridge add name=bridge-lan\n# Snapshot generated by AUDIRA NetOps AI',
    createdBy: req.user?.username || 'admin',
    createdAt: new Date().toISOString(),
  };

  BACKUPS_STORE.unshift(newBackup);
  res.status(201).json({ success: true, data: newBackup, message: 'Backup created successfully' });
});

/**
 * GET /api/v1/backups/:id/download - Download backup file content
 */
backupRouter.get('/:id/download', authenticateJwt, requirePermission('config.read'), (req: Request, res: Response) => {
  const backup = BACKUPS_STORE.find(b => b.id === req.params.id);
  if (!backup) {
    res.status(404).json({ success: false, code: 'BACKUP_FAILED', message: 'Backup file not found' });
    return;
  }

  res.setHeader('Content-Disposition', `attachment; filename="${backup.filename}"`);
  res.setHeader('Content-Type', 'text/plain');
  res.send(backup.content || '# Encrypted binary backup stream');
});
